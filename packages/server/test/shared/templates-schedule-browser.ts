import assert from 'node:assert/strict';
import ExcelJS from 'exceljs';
import {withBrowserPage} from './browser-fixture.ts';
await withBrowserPage(async(page,base)=>{
  const token=(await fetch(base+'/api/session').then(r=>r.json())).data.token;
  async function api(path:string,method='GET',body?:object|FormData){
    const form=body instanceof FormData;
    const response=await fetch(base+path,{method,headers:{'x-workbench-token':token,...body&&!form?{'content-type':'application/json'}:{}},body:form?body:body?JSON.stringify(body):undefined});
    const result=await response.json();assert.ok(response.ok,result.error?.message||path);return result.data;
  }
  const wt=(await api('/api/work-types')).items.find((t:{code:string})=>t.code==='safety-report');
  const book=new ExcelJS.Workbook();book.addWorksheet('合成记录').addRow(['内容']);
  const bytes=await book.xlsx.writeBuffer(), form=new FormData();form.append('name','合成例会记录');form.append('workTypeId',String(wt.id));form.append('file',new Blob([new Uint8Array(bytes)]),'合成记录.xlsx');
  const tpl=(await api('/api/templates/upload','POST',form)).items[0].template;
  const work=await api('/api/workbenches','POST',{workTypeId:wt.id,publishedConfigId:wt.published_config_id,name:'合成办理',firstPeriod:'2025-10',templateIds:[tpl.id]});
  const listPath='/api/workbenches/'+work.id+'/periods';
  const initial=await api(listPath); const id=initial.items.find((p:{report_period:string})=>p.report_period==='2025-10').id;
  const url=base+'/#/workbench?id='+work.id+'&periodId='+id;
  const open=async(p:any)=>{await p.goto(url);await p.locator('.period-workspace').waitFor();};
  const btn=(p:any,name:string)=>p.getByRole('button',{name,exact:true});
  const options=(p:any)=>p.getByRole('checkbox',{name:/合成例会记录/});
  const req=(p:any)=>p.getByLabel('必备材料（一行一项）',{exact:true});
  const openRule=async(p:any)=>{await btn(p,'高级排期设置').click();await req(p).waitFor();};
  const nav=()=>page.getByText('工作台首页',{exact:true}).first().click();
  const choose='选择 / 调整模板',saveTemplates='保存模板选择';
  const savedSnapshot=async()=>JSON.parse((await api('/api/periods/'+id)).snapshot);
  const originalPeriod=await savedSnapshot();
  await open(page);
  await btn(page,choose).click();assert.equal(await options(page).isChecked(),true);
  await options(page).uncheck();await btn(page,'收起选择').click();
  await page.getByText('模板选择尚未保存，展开后可继续核对。',{exact:true}).waitFor();
  await nav();const guard=page.getByRole('dialog',{name:'还有未保存的修改'});
  await guard.getByRole('button',{name:'继续编辑',exact:true}).click();await btn(page,choose).click();
  assert.equal(await options(page).isChecked(),false);
  const templatePath='**/api/periods/'+id+'/templates';
  await page.route(templatePath,(route:any)=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({ok:false,error:{message:'合成模板写入故障'}})}));
  await btn(page,saveTemplates).click();
  await page.getByRole('alert').filter({hasText:'合成模板写入故障'}).waitFor();
  assert.equal(await options(page).isChecked(),false);
  assert.deepEqual((await savedSnapshot()).templates,originalPeriod.templates);
  await page.unroute(templatePath);
  await nav();await guard.getByRole('button',{name:'保存并离开',exact:true}).click();
  await page.locator('#home-inbox').waitFor();assert.deepEqual((await savedSnapshot()).templates,[]);
  await open(page);await btn(page,choose).click();assert.equal(await options(page).isChecked(),false);
  await options(page).check();await nav();await guard.getByRole('button',{name:'不保存离开',exact:true}).click();
  await page.locator('#home-inbox').waitFor();await open(page);await btn(page,choose).click();assert.equal(await options(page).isChecked(),false);
  await btn(page,'收起选择').click();
  console.log('模板：收起和离开继续保留勾选，写入失败未改快照，重试保存、放弃及重开已核对。');

  await openRule(page);
  const day=(p:any)=>p.getByLabel('截止日号',{exact:true}),remind=(p:any)=>p.getByLabel('提前提醒天数',{exact:true});
  await day(page).fill('19');
  const refreshed=page.waitForResponse((r:any)=>r.url().endsWith(listPath)&&r.request().method()==='GET');
  await btn(page,'补齐期次').click();await refreshed;
  assert.equal(await day(page).inputValue(),'19');
  await btn(page,'高级排期设置').click();await guard.getByRole('button',{name:'继续编辑',exact:true}).click();
  assert.equal(await day(page).inputValue(),'19');
  const other=await page.context().browser().newPage();other.setDefaultTimeout(7500);
  try{
    await open(other);await openRule(other);await remind(other).fill('7');
    const rulePath=listPath+'/rule';
    const result=(p:any)=>p.waitForResponse((r:any)=>r.url().endsWith(rulePath)&&r.request().method()==='PUT');
    let response=result(page);await btn(page,'保存规则').click();assert.equal((await response).status(),200);
    const version=(await api(listPath)).rule.version;
    response=result(other);await btn(other,'保存规则').click();assert.equal((await response).status(),409);
    await btn(other,'保留本页修改并核对').waitFor();assert.equal((await api(listPath)).rule.due_day,19);
    assert.equal((await api(listPath)).rule.remind_days,initial.rule.remind_days);
    await btn(other,'保留本页修改并核对').click();
    assert.equal(await day(other).inputValue(),'19');assert.equal(await remind(other).inputValue(),'7');
    const fail='**'+rulePath;
    await other.route(fail,(route:any)=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({ok:false,error:{message:'合成排期保存失败'}})}));
    await btn(other,'保存规则').click();await other.getByRole('alert').filter({hasText:'合成排期保存失败'}).waitFor();
    assert.equal((await api(listPath)).rule.version,version);assert.equal(await remind(other).inputValue(),'7');
    await other.unroute(fail);response=result(other);await btn(other,'保存规则').click();assert.equal((await response).status(),200);
    const saved=(await api(listPath)).rule;assert.equal(saved.due_day,19);assert.equal(saved.remind_days,7);assert.equal(saved.version,version+1);
    await other.reload();await other.locator('.period-workspace').waitFor();await openRule(other);
    assert.equal(await day(other).inputValue(),'19');assert.equal(await remind(other).inputValue(),'7');
    const snapshot=await savedSnapshot();assert.equal(snapshot.due_day,originalPeriod.due_day);assert.equal(snapshot.remind_days,originalPeriod.remind_days);
    console.log('排期：刷新不丢输入，双窗口旧版本拒绝并保留字段，明确核对、失败重试、规则重开及已有期次快照通过。');
  }finally{await other.close();}
});
